import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:4173/', { waitUntil:'networkidle' });
await page.waitForTimeout(1500);
await page.screenshot({ path:'tmp/menu2.png' });
console.log('menu dims', await page.evaluate(()=>({h:document.body.scrollHeight,w:document.body.scrollWidth})));
console.log('errors', errors);
await page.getByRole('button',{name:/Initiate Drop/i}).click();
await page.waitForTimeout(3800);
await page.keyboard.press('KeyW');
await page.mouse.move(900, 450);
await page.mouse.down();
await page.waitForTimeout(800);
await page.mouse.up();
await page.keyboard.press('KeyD');
await page.waitForTimeout(600);
await page.screenshot({ path:'tmp/game2.png' });
console.log('errors2', errors);
console.log('hud score text', await page.locator('body').innerText().then(t=>t.slice(0,260)));
await browser.close();
