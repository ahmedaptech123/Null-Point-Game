import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const errors = [];
const desktop = await browser.newPage({ viewport: { width: 1440, height: 900 } });
desktop.on('pageerror', e => errors.push('PAGE ' + e.message));
desktop.on('console', m => { if (m.type()==='error') errors.push('CONSOLE ' + m.text()); });
await desktop.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle' });
await desktop.waitForTimeout(1500);
await desktop.screenshot({ path: 'tmp/menu3.png' });
await desktop.getByRole('button', { name: /Initiate Drop/i }).click({ noWaitAfter: true, force: true, timeout: 8000 }).catch(e=>console.log('click issue', e.message.split('\n')[0]));
await desktop.waitForTimeout(16000);
await desktop.screenshot({ path: 'tmp/game3.png' });
console.log('desktop errors', errors);
console.log('game text', (await desktop.locator('body').innerText()).slice(0, 200));
const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
mobile.on('pageerror', e => errors.push('MOBILE PAGE ' + e.message));
await mobile.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle' });
await mobile.waitForTimeout(1500);
await mobile.screenshot({ path: 'tmp/mobile-menu.png', fullPage: false });
console.log('mobile dims', await mobile.evaluate(() => ({ h: document.body.scrollHeight, w: document.body.scrollWidth })));
await mobile.getByRole('button', { name: /Initiate Drop/i }).click({ noWaitAfter: true, force: true, timeout: 8000 }).catch(e=>console.log('m click issue', e.message.split('\n')[0]));
await mobile.waitForTimeout(12000);
await mobile.screenshot({ path: 'tmp/mobile-game.png' });
console.log('errors all', errors);
await browser.close();
