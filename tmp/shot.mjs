import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errors = [];
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', e => errors.push('PAGE: ' + e.message));
await page.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle', timeout: 30000 }).catch(e => console.log('goto', e.message));
await page.waitForTimeout(2500);
await page.screenshot({ path: 'tmp/menu.png', fullPage: false });
console.log('MENU TITLE', await page.title());
console.log('ERRORS1', JSON.stringify(errors));
const btn = page.getByRole('button', { name: /Initiate Drop/i });
console.log('deploy count', await btn.count());
await btn.first().click();
await page.waitForTimeout(5000);
await page.screenshot({ path: 'tmp/game.png', fullPage: false });
console.log('ERRORS2', JSON.stringify(errors));
console.log('canvas', await page.locator('canvas').count());
console.log('body text', (await page.locator('body').innerText()).slice(0, 500));
await browser.close();
